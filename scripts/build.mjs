// Bundles src/ (TypeScript) into dist/index.js: plain ES module JavaScript with no imports, so the classifier
// runs from node_modules (Node will not strip types there), in Cloudflare Workers and in browsers.
// dist/ is committed; tests/unit/dist.test.js fails when it is out of date, and CI rebuilds it.
//   node scripts/build.mjs          write dist/index.js
//   node scripts/build.mjs --check  exit 1 if dist/index.js differs from a fresh build
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const out = await build({
  entryPoints: ['src/index.ts'],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  write: false,
  legalComments: 'none',
  banner: { js: '// Generated by scripts/build.mjs from src/. Do not edit.' }
});
const code = out.outputFiles[0].text;
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync('dist/index.js', 'utf8');
  } catch {}
  if (current !== code) {
    console.error('dist/index.js is out of date: run node scripts/build.mjs');
    process.exit(1);
  }
  console.log('dist/index.js is current');
} else {
  mkdirSync('dist', { recursive: true });
  writeFileSync('dist/index.js', code);
  console.log(`dist/index.js: ${code.length} bytes`);
}
